from itertools import product, permutations

def f(w,x,y,z): # Определяем логическую функцию F по формуле задачи
    return (not(w <= (x == y))) and (z <= x)

for x1,x2,x3,x4,x5,x6 in product([0,1], repeat=6): # Перебираем все варианты пропусков в таблице (6 пропусков)
    t = (
        (x1,0,1,0,1),      # Первая строка: x1,0,1,0,1
        (0,x2,x3,0,1),     # Вторая строка: 0,x2,x3,0,1
        (x4,1,1,x5,1)      # Третья строка: x4,1,1,x5,1
    )
    if len(t) == len(set(t)): # Проверяем, что все строки таблицы различны
        for p in permutations('wxyz', r=4): # Перебираем все перестановки переменных
            if all(f(**dict(zip(p,l))) == l[-1] for l in t): # Проверяем выполнение функции для каждой строки таблицы
                print(*p, sep='') # Выводим найденную перестановку букв без разделителей
                exit() # Завершаем выполнение программы после вывода ответа